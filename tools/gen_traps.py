"""Write generator/traps.cpp: a trap for each function the compiled objects need and nothing defines.

Usage: python3 -I tools/gen_traps.py <debug-build-dir>/CMakeFiles/kaepora-generator.dir generator/traps.cpp
On Windows: python -I tools/gen_traps.py --windows <build-dir> generator/traps_windows.cpp

The imported sources hold game and GUI code next to the generator code. The generator never calls that code,
but the linker still needs a definition for every function it references. Each trap aborts with the symbol name.
A missing symbol used as data, or as a function pointer not listed below, must be defined by hand in generator/.
Read the objects of a Debug build: optimised objects drop some references that a Debug build still needs.

On Windows the linker names what it misses. The script writes generator/traps_windows.cpp with no traps, links
kaepora-seedgen in the build folder, writes a trap for each name the linker reports, and links again. The build
folder must use clang-cl, and the script must run in the Visual Studio environment that configured it. It stops on a
C name the Linux traps do not hold and on a C++ variable, which must be checked or defined by hand.
"""

import os
import pathlib
import re
import subprocess
import sys

# Libraries the generator links against, found on the compiler's search path.
LIBRARIES = ["libstdc++.so", "libm.so.6", "libc.so.6", "libgcc_s.so.1", "libspdlog.so", "libfmt.so"]
# Draw functions whose address the item table stores.
ADDRESS_TAKEN_FUNCTIONS = re.compile(r"^(Randomizer_Draw\w+|_Z\d+EnItem00_DrawRandomizedItem\w*)$")
LINKER_DEFINED = {"_GLOBAL_OFFSET_TABLE_", "__dso_handle"}
HEADER = """\
// Generated by tools/gen_traps.py. Do not edit.
// Game and GUI functions that the imported sources reference and the generator never calls.
#include <cstdio>
#include <cstdlib>

static void Trap(const char* symbol) {
    std::fprintf(stderr, "called game-only function %s\\n", symbol);
    std::abort();
}

#define TRAP(symbol)                   \\
    void trap_##symbol() asm(#symbol); \\
    void trap_##symbol() {             \\
        Trap(#symbol);                 \\
    }

"""
WINDOWS_HEADER = """\
// Generated by tools/gen_traps.py. Do not edit.
// Game and GUI functions that the imported sources reference and the generator never calls, by their names in a
// Windows build. The linker resolves each name that nothing defines to its trap.
#include <cstdio>
#include <cstdlib>

static void Trap(const char* symbol) {
    std::fprintf(stderr, "called game-only function %s\\n", symbol);
    std::abort();
}

#define TRAP(number, symbol)                                             \\
    extern "C" void trap_##number() {                                    \\
        Trap(symbol);                                                    \\
    }                                                                    \\
    __pragma(comment(linker, "/alternatename:" symbol "=trap_" #number))

"""


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def link_seedgen(build):
    return subprocess.run(["cmake", "--build", build, "--target", "kaepora-seedgen"], capture_output=True, text=True,
                          env={**os.environ, "LINK": "/demangle:no /errorlimit:0"})


def windows(build, out_path):
    out = pathlib.Path(out_path)
    out.write_text(WINDOWS_HEADER, newline="\n")
    result = link_seedgen(build)
    missing = sorted(set(re.findall(r"undefined symbol: (\S+)", result.stdout)))
    if not missing:
        print(result.stdout, result.stderr, "the link reported no missing symbol", sep="\n", file=sys.stderr)
        return 1
    # In MSVC's name of a C++ symbol, a digit right after the qualified name marks a variable. A C name tells nothing,
    # so it must be one the Linux traps checked.
    linux = set(re.findall(r"^TRAP\((\w+)\)$", (out.parent / "traps.cpp").read_text(), re.MULTILINE))
    data = [s for s in missing if re.match(r"\?[^@]+(?:@[^@]+)*@@\d", s)]
    unchecked = [s for s in missing if not s.startswith("?") and s not in linux]
    if data or unchecked:
        print("define these by hand in generator/, they are data or Windows alone misses them:", file=sys.stderr)
        for s in data + unchecked:
            print(f"  {s}", file=sys.stderr)
        return 1

    out.write_text(WINDOWS_HEADER + "".join(f'TRAP({n}, "{s}")\n' for n, s in enumerate(missing)), newline="\n")
    result = link_seedgen(build)
    if result.returncode != 0:
        print(result.stdout, result.stderr, sep="\n", file=sys.stderr)
        return 1
    print(f"{len(missing)} traps written to {out_path}")
    return 0


def main():
    if sys.argv[1] == "--windows":
        return windows(*sys.argv[2:])
    objdir, out_path = sys.argv[1:]
    objects = sorted(str(p) for p in pathlib.Path(objdir).rglob("*.o") if p.name != "traps.cpp.o")
    defined, undefined = set(), set()
    for line in run("nm", "-g", *objects).splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":
            undefined.add(parts[1])
        elif len(parts) == 3:
            defined.add(parts[2])
    for name in LIBRARIES:
        library = run("c++", f"-print-file-name={name}").strip()
        for line in run("nm", "-D", "--defined-only", library).splitlines():
            defined.add(line.split()[-1].split("@")[0])
    missing = sorted(undefined - defined - LINKER_DEFINED)

    relocations = {}
    for obj in objects:
        for line in run("objdump", "-r", obj).splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[1].startswith("R_X86_64"):
                relocations.setdefault(re.split(r"[-+]0x", parts[2])[0], set()).add(parts[1])
    data = [s for s in missing if relocations[s] - {"R_X86_64_PLT32"} and not ADDRESS_TAKEN_FUNCTIONS.match(s)]
    if data:
        print("define these by hand in generator/, they are not plain calls:", file=sys.stderr)
        for s in data:
            print(f"  {s}  {sorted(relocations[s])}", file=sys.stderr)
        return 1

    pathlib.Path(out_path).write_text(HEADER + "".join(f"TRAP({s})\n" for s in missing))
    print(f"{len(missing)} traps written to {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
