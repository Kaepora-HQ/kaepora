"""Write generator/traps.cpp: a trap for each function the compiled objects need and nothing defines.

Usage: python3 -I tools/gen_traps.py <debug-build-dir>/CMakeFiles/kaepora-seedgen.dir generator/traps.cpp

The imported sources hold game and GUI code next to the generator code. The generator never calls that code,
but the linker still needs a definition for every function it references. Each trap aborts with the symbol name.
A missing symbol used as data, or as a function pointer not listed below, must be defined by hand in generator/.
Read the objects of a Debug build: optimised objects drop some references that a Debug build still needs.
"""

import pathlib
import re
import subprocess
import sys

# Libraries the generator links against, found on the compiler's search path.
LIBRARIES = ["libstdc++.so", "libm.so.6", "libc.so.6", "libgcc_s.so.1", "libspdlog.so", "libfmt.so"]
# Draw functions whose address the item table stores.
ADDRESS_TAKEN_FUNCTIONS = re.compile(r"^(Randomizer_Draw\w+|_Z\d+EnItem00_DrawRandomizedItem\w*)$")
LINKER_DEFINED = {"_GLOBAL_OFFSET_TABLE_", "__dso_handle"}
HEADER = """\
// Generated by tools/gen_traps.py. Do not edit.
// Game and GUI functions that the imported sources reference and the generator never calls.
#include <cstdio>
#include <cstdlib>

static void Trap(const char* symbol) {
    std::fprintf(stderr, "kaepora-seedgen: called game-only function %s\\n", symbol);
    std::abort();
}

#define TRAP(symbol)                   \\
    void trap_##symbol() asm(#symbol); \\
    void trap_##symbol() {             \\
        Trap(#symbol);                 \\
    }

"""


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def main():
    objdir, out_path = sys.argv[1:]
    objects = sorted(str(p) for p in pathlib.Path(objdir).rglob("*.o") if p.name != "traps.cpp.o")
    defined, undefined = set(), set()
    for line in run("nm", "-g", *objects).splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":
            undefined.add(parts[1])
        elif len(parts) == 3:
            defined.add(parts[2])
    for name in LIBRARIES:
        library = run("c++", f"-print-file-name={name}").strip()
        for line in run("nm", "-D", "--defined-only", library).splitlines():
            defined.add(line.split()[-1].split("@")[0])
    missing = sorted(undefined - defined - LINKER_DEFINED)

    relocations = {}
    for obj in objects:
        for line in run("objdump", "-r", obj).splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[1].startswith("R_X86_64"):
                relocations.setdefault(re.split(r"[-+]0x", parts[2])[0], set()).add(parts[1])
    data = [s for s in missing if relocations[s] - {"R_X86_64_PLT32"} and not ADDRESS_TAKEN_FUNCTIONS.match(s)]
    if data:
        print("define these by hand in generator/, they are not plain calls:", file=sys.stderr)
        for s in data:
            print(f"  {s}  {sorted(relocations[s])}", file=sys.stderr)
        return 1

    pathlib.Path(out_path).write_text(HEADER + "".join(f"TRAP({s})\n" for s in missing))
    print(f"{len(missing)} traps written to {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
